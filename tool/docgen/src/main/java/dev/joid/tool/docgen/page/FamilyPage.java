package dev.joid.tool.docgen.page;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.google.gson.Gson;

import dev.joid.tool.docgen.description.DescriptionFile;
import dev.joid.tool.docgen.model.ApiType;
import dev.joid.tool.docgen.model.Family;
import dev.joid.tool.docgen.model.TypeKind;
import dev.joid.tool.docgen.report.Coverage;

public final class FamilyPage {

	private static final String PATH = "documentation/reference/families.md";

	private static final String NODE   = "dev.joid.lib.ui.node.Node";
	private static final String EFFECT = "dev.joid.lib.ui.node.effect.NodeEffect";

	private static final String[] BACKENDS = {"LWJGL 2", "LWJGL 3", "Vulkan"};

	private final PageRegistry                 registry;
	private final Map<String, DescriptionFile> descriptions;
	private final LinkChecker                  links;
	private final Coverage                     coverage;
	private final Map<String, String>          intros;

	private FamilyPage(final PageRegistry registry, final Map<String, DescriptionFile> descriptions, final LinkChecker links, final Coverage coverage) {
		this.registry     = registry;
		this.descriptions = descriptions;
		this.links        = links;
		this.coverage     = coverage;
		this.intros       = new LinkedHashMap<>();
	}

	public static FamilyPage create(final PageRegistry registry, final Map<String, DescriptionFile> descriptions, final LinkChecker links, final Coverage coverage, final File file) throws IOException {
		final FamilyPage page = new FamilyPage(registry, descriptions, links, coverage);
		if (file.isFile()) {
			String key = null;
			final StringBuilder text = new StringBuilder();
			for (final String line : Files.readAllLines(file.toPath(), StandardCharsets.UTF_8)) {
				if (line.startsWith("## ")) {
					page.store(key, text);
					key = line.substring(3).trim();
					continue;
				}
				text.append(line).append('\n');
			}
			page.store(key, text);
		}
		return page;
	}

	public List<Map<String, Object>> write(final File docs) throws IOException {
		final Map<Family, List<TypePage>> families = new LinkedHashMap<>();
		for (final Family family : Family.values()) {
			families.put(family, new ArrayList<>());
		}
		this.registry.all().forEach(page -> families.get(page.getFamily()).add(page));
		families.values().removeIf(List::isEmpty);

		final List<Map<String, Object>> sidebar = new ArrayList<>();
		final StringBuilder index = new StringBuilder("---\ntitle: \"Reference\"\ndescription: \"Every public type of JOID, grouped by family.\"\ngenre: reference\ntopic: reference\nsidebar:\n  order: 0\n---\n\n<!-- Generated by tool-docgen from the sources and ").append(FamilyPage.PATH).append(". Do not edit. -->\n\n");
		index.append("Every public class, interface, enum and annotation of JOID, with its properties, methods, events and default values.\n");
		index.append("Every warning and exception message is on [Warnings and errors](/reference/errors/), and every term on the [Glossary](/reference/glossary/).\n\n");
		index.append("| Family | What it holds | Types |\n|---|---|---|\n");
		for (final Map.Entry<Family, List<TypePage>> family : families.entrySet()) {
			final String key = family.getKey().getId();
			final String label = family.getKey().getLabel();
			final String url = "/reference/" + key + "/";
			final String intro = this.intros.get(key);
			final String path = FamilyPage.PATH + " (" + key + ")";
			this.coverage.expect("families", FamilyPage.PATH, key, intro != null);
			final String first = intro == null ? "" : intro.split("\n")[0].trim();
			index.append("| [").append(label).append("](").append(url).append(") | ").append(this.links.resolve(first, path).replace("|", "\\|")).append(" | ").append(family.getValue().size()).append(" |\n");

			final List<TypePage> main = new ArrayList<>();
			final List<TypePage> supporting = new ArrayList<>();
			for (final TypePage page : family.getValue()) {
				(FamilyPage.isSupporting(page.getType()) ? supporting : main).add(page);
			}
			main.sort(Comparator.comparing(TypePage::getTitle, String.CASE_INSENSITIVE_ORDER));
			supporting.sort(Comparator.comparing(TypePage::getTitle, String.CASE_INSENSITIVE_ORDER));

			final StringBuilder page = new StringBuilder("---\ntitle: ").append(new Gson().toJson(label)).append("\ndescription: ").append(new Gson().toJson(first.isEmpty() ? "Reference of the " + label + " family." : first.replaceAll("\\[([^\\]]*)\\]\\([^)]*\\)", "$1").replaceAll("\\[\\[([A-Za-z0-9_.$]+)(?:#[A-Za-z0-9_<>]+(?:\\([A-Za-z0-9_.$\\[\\], ]*\\))?)?\\]\\]", "$1").replace("`", ""))).append("\ngenre: reference\ntopic: reference\nsidebar:\n  order: 0\n---\n\n<!-- Generated by tool-docgen from the sources and ").append(FamilyPage.PATH).append(". Do not edit. -->\n\n");
			if (intro != null) {
				page.append(this.links.resolve(intro, path)).append("\n\n");
			}

			this.matrix(main, page);
			final List<TypePage> related = this.related(main);
			if (!supporting.isEmpty() || !related.isEmpty()) {
				page.append("## Main types\n\n");
			}
			this.table(main, page);
			if (!related.isEmpty()) {
				page.append("## Related types\n\nThe interfaces, enums and helper classes of this family that the main types use.\n\n");
				this.table(related, page);
			}
			if (!supporting.isEmpty()) {
				page.append("## Supporting types\n\nNested types and listeners that the main types use.\n\n");
				this.table(supporting, page);
			}
			FamilyPage.write(new File(docs, "reference/" + key + "/index.md"), page.toString());

			final Map<String, Object> link = new LinkedHashMap<>();
			link.put("label", label);
			link.put("link", url);
			sidebar.add(link);
		}

		for (final String key : this.intros.keySet()) {
			if (families.keySet().stream().noneMatch(family -> family.getId().equals(key))) {
				this.coverage.unknown(FamilyPage.PATH, key);
			}
		}
		FamilyPage.write(new File(docs, "reference/index.md"), index.toString());
		return sidebar;
	}

	private void table(final List<TypePage> pages, final StringBuilder out) {
		out.append("| Type | Kind | Summary |\n|---|---|---|\n");
		for (final TypePage type : pages) {
			final DescriptionFile description = this.descriptions.get(type.getType().getFqcn());
			final String summary = description == null ? "" : this.links.resolve(description.getSummary(), "documentation/reference/" + type.getType().getFqcn() + ".md").replace("|", "\\|");
			out.append("| [`").append(type.getTitle()).append("`](").append(type.getUrl()).append(") | ").append(type.getType().getKind().getKeyword()).append(" | ").append(summary).append(" |\n");
		}
		out.append('\n');
	}

	private void matrix(final List<TypePage> pages, final StringBuilder out) {
		final List<TypePage> nodes = new ArrayList<>();
		final List<TypePage> effects = new ArrayList<>();
		for (final TypePage page : pages) {
			final List<String> ancestors = this.ancestors(page.getType());
			if (page.getType().getFqcn().equals(FamilyPage.NODE) || ancestors.contains(FamilyPage.NODE)) {
				nodes.add(page);
			} else if (ancestors.contains(FamilyPage.EFFECT)) {
				effects.add(page);
			}
		}

		if (nodes.size() >= 3) {
			final List<String> skins = new ArrayList<>();
			for (final TypePage page : nodes) {
				if (page.getType().isAbstractType() && !page.getType().getFqcn().equals(FamilyPage.NODE)) {
					skins.add("[`" + page.getTitle() + "`](" + page.getUrl() + ")");
				}
			}

			if (!skins.isEmpty()) {
				final String names = skins.size() == 1 ? skins.get(0) : String.join(", ", skins.subList(0, skins.size() - 1)) + " and " + skins.get(skins.size() - 1);
				out.append(names).append(skins.size() == 1 ? " needs" : " need").append(" a skin, a subclass that draws the node: see [Give your controls a look](/use/learn/going-further/ui-kit/).\n\n");
			}
		}

		if (effects.size() >= 3) {
			final Map<TypePage, List<String>> supported = new LinkedHashMap<>();
			effects.forEach(page -> supported.put(page, Arrays.asList(PageWriter.backendsOf(page.getType(), this.descriptions.get(page.getType().getFqcn())).split(",\\s*"))));
			if (supported.values().stream().allMatch(backends -> backends.containsAll(Arrays.asList(FamilyPage.BACKENDS)))) {
				out.append("Every effect of this family runs on the three backends: ").append(FamilyPage.BACKENDS[0]).append(", ").append(FamilyPage.BACKENDS[1]).append(" and ").append(FamilyPage.BACKENDS[2]).append(".\n\n");
				return;
			}

			out.append("## Backends\n\n| Effect | ").append(String.join(" | ", FamilyPage.BACKENDS)).append(" |\n|---|---|---|---|\n");
			for (final Map.Entry<TypePage, List<String>> entry : supported.entrySet()) {
				out.append("| [`").append(entry.getKey().getTitle()).append("`](").append(entry.getKey().getUrl()).append(")");
				for (final String backend : FamilyPage.BACKENDS) {
					out.append(" | ").append(entry.getValue().contains(backend) ? "yes" : "no");
				}
				out.append(" |\n");
			}
			out.append('\n');
		}
	}

	private List<TypePage> related(final List<TypePage> main) {
		final Map<String, List<TypePage>> roots = new LinkedHashMap<>();
		for (final TypePage page : main) {
			if (page.getType().getKind() != TypeKind.CLASS) {
				continue;
			}

			roots.computeIfAbsent(page.getType().getFqcn(), key -> new ArrayList<>()).add(page);
			for (final ApiType ancestor : TypePage.ancestors(page.getType(), this.registry.getTypes())) {
				if (ancestor.getKind() == TypeKind.CLASS) {
					roots.computeIfAbsent(ancestor.getFqcn(), key -> new ArrayList<>()).add(page);
				}
			}
		}

		String root = null;
		for (final Map.Entry<String, List<TypePage>> entry : roots.entrySet()) {
			final int size = root == null ? 0 : roots.get(root).size();
			if (entry.getValue().size() > size || entry.getValue().size() == size && entry.getValue().stream().anyMatch(page -> page.getType().getFqcn().equals(entry.getKey()))) {
				root = entry.getKey();
			}
		}

		final List<TypePage> related = new ArrayList<>();
		if (root == null || roots.get(root).size() < 3 || roots.get(root).size() * 2 <= main.size()) {
			return related;
		}

		final List<TypePage> head = roots.get(root);
		for (final TypePage page : main) {
			if (!head.contains(page)) {
				related.add(page);
			}
		}
		main.removeAll(related);

		for (final TypePage page : main) {
			if (page.getType().getFqcn().equals(root)) {
				main.remove(page);
				main.add(0, page);
				break;
			}
		}
		return related;
	}

	private List<String> ancestors(final ApiType type) {
		final List<String> fqcns = new ArrayList<>();
		TypePage.ancestors(type, this.registry.getTypes()).forEach(ancestor -> fqcns.add(ancestor.getFqcn()));
		return fqcns;
	}

	private void store(final String key, final StringBuilder text) {
		if (key != null && text.toString().trim().length() > 0) {
			this.intros.put(key, text.toString().trim());
		}
		text.setLength(0);
	}

	private static boolean isSupporting(final ApiType type) {
		final String name = type.getName();
		return name.contains(".") || type.getKind() == TypeKind.INTERFACE && (name.endsWith("Callback") || name.endsWith("Listener"));
	}

	private static void write(final File file, final String content) throws IOException {
		file.getParentFile().mkdirs();
		Files.write(file.toPath(), content.getBytes(StandardCharsets.UTF_8));
	}

}