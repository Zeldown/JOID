import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DOCUMENTATION = fileURLToPath(new URL('..', import.meta.url));
const TERMS = join(DOCUMENTATION, 'rules', 'terms.md');
const PAGE = join(DOCUMENTATION, 'src', 'content', 'docs', 'reference', 'glossary.md');

export function glossaryTerms() {
	const terms = [];
	let current = null;
	for (const line of readFileSync(TERMS, 'utf-8').split(/\r?\n/)) {
		const heading = line.match(/^## (.+)$/);
		if (heading) {
			current = { name: heading[1].trim(), text: [], avoid: [], see: null };
			terms.push(current);
		} else if (current && line.startsWith('Avoid:')) {
			current.avoid = line.slice(6).split(',').map((word) => word.trim()).filter((word) => word.length > 0);
		} else if (current && line.startsWith('See:')) {
			current.see = line.slice(4).trim();
		} else if (current) {
			current.text.push(line);
		}
	}
	return terms;
}

function slug(text) {
	return text.toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, '').trim().replace(/\s/g, '-');
}

function title(url) {
	const [page, hash] = url.split('#');
	const base = join(DOCUMENTATION, 'src', 'content', 'docs', page.replace(/^\/|\/$/g, ''));
	const file = [`${base}.md`, `${base}.mdx`, join(base, 'index.md'), join(base, 'index.mdx')].find((candidate) => existsSync(candidate));
	if (!file) {
		console.warn(`[JOID] terms.md: the See: page ${url} does not exist yet, the glossary names its URL`);
		return url;
	}
	const source = readFileSync(file, 'utf-8');
	if (hash) {
		const heading = source.split(/\r?\n/).map((line) => line.match(/^#{2,4} (.+)$/)).find((match) => match && slug(match[1]) === hash);
		if (heading) {
			return heading[1].replace(/`/g, '');
		}
	}
	return JSON.parse(source.match(/^title: (".*")\s*$/m)?.[1] ?? '""') || page;
}

function anchor(name) {
	return `term-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
}

export function generateGlossary() {
	const out = ['---', 'title: "Glossary"', 'description: "The terms used in this documentation."', 'genre: reference', 'topic: reference', 'sidebar:', '  order: 2', '---', '', '<!-- Generated by npm run docgen from documentation/rules/terms.md. Do not edit. -->', ''];
	for (const term of glossaryTerms().sort((left, right) => left.name.localeCompare(right.name))) {
		out.push(`<a id="${anchor(term.name)}"></a>`, '', `### ${term.name}`, '', term.text.join('\n').trim());
		if (term.see) {
			out.push('', `See [${title(term.see)}](${term.see}).`);
		}
		out.push('');
	}
	writeFileSync(PAGE, `${out.join('\n')}\n`);
}