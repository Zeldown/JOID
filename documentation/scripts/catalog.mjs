import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { withLock } from './gradle.mjs';

const DOCUMENTATION = fileURLToPath(new URL('..', import.meta.url));
const CATALOG = join(DOCUMENTATION, 'catalog', 'catalog.json');
const INDEX = join(DOCUMENTATION, 'src', 'generated', 'reference-index.json');
const PAGE = join(DOCUMENTATION, 'src', 'content', 'docs', 'use', 'catalog.md');
const SCENARIOS = join(DOCUMENTATION, 'examples', 'captures');
const CAPTURES = join(DOCUMENTATION, 'public', 'captures');
const EXAMPLES = 'https://github.com/Zeldown/JOID/blob/main/documentation/examples/src/main/java/';
const SKINS = '/use/learn/going-further/ui-kit/';
const CARD = { width: 340, height: 300, columns: 5, x: 40, y: 40, stepX: 370, stepY: 340 };

export function loadCatalog() {
	return JSON.parse(readFileSync(CATALOG, 'utf-8'));
}

export function loadIndex() {
	const index = JSON.parse(readFileSync(INDEX, 'utf-8')).types;
	const byFqcn = {};
	for (const entry of Object.values(index)) {
		byFqcn[entry.fqcn] = entry;
	}
	return { byName: index, byFqcn };
}

export function slug(text) {
	return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

export function cardName(card) {
	return card.name ?? card.type.slice(card.type.lastIndexOf('.') + 1);
}

export function shotName(section, card) {
	return `catalog-${section.id}-${slug(cardName(card))}`;
}

function escape(text) {
	return String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function reference(card, index) {
	if (card.type) {
		const entry = index.byFqcn[card.type];
		if (!entry) {
			throw new Error(`catalog: ${card.type} has no reference page`);
		}
		return { url: entry.url, entry };
	}
	const [name, member] = card.reference.split('#');
	const entry = index.byName[name];
	if (!entry) {
		throw new Error(`catalog: unknown reference type ${name}`);
	}
	if (member && !entry.members[member]) {
		throw new Error(`catalog: ${name} has no member ${member}`);
	}
	return { url: member ? `${entry.url}#${entry.members[member]}` : entry.url, entry };
}

function scenario(section) {
	const lines = ['# Generated by npm run docgen from documentation/catalog/catalog.json. Do not edit.'];
	if (section.commands) {
		for (const card of section.cards) {
			const shot = shotName(section, card);
			lines.push(`# crop ${shot} ${section.crop.join(' ')}`);
			if (card.hold) {
				lines.push(`# hold ${shot} ${card.hold}`);
			}
			if (card.still !== undefined) {
				lines.push(`# still ${shot} ${card.still}`);
			}
			lines.push(...section.commands.map((command) => command.replaceAll('{shot}', shot)));
		}
		return lines;
	}
	lines.push(`ui ${section.scene}`, 'wait 100');
	section.cards.forEach((card, position) => {
		if (card.capture === false) {
			return;
		}
		const shot = shotName(section, card);
		const x = CARD.x + (position % CARD.columns) * CARD.stepX;
		const y = CARD.y + Math.floor(position / CARD.columns) * CARD.stepY;
		lines.push(`# crop ${shot} ${x} ${y} ${CARD.width} ${CARD.height}`);
		if (card.film) {
			if (card.hold) {
				lines.push(`# hold ${shot} ${card.hold}`);
			}
			if (card.still !== undefined) {
				lines.push(`# still ${shot} ${card.still}`);
			}
			lines.push(card.fps ? `# film ${shot} ${card.fps}` : `# film ${shot}`, `wait ${card.film}`, 'cut');
		} else {
			lines.push(`shot ${shot}`);
		}
	});
	return lines;
}

function page(catalog, index) {
	const out = ['---', 'title: "Catalog"', 'description: "Every node, control, effect, transition, easing curve, text effect and cursor, with a capture."', 'genre: reference', 'tableOfContents:', '  maxHeadingLevel: 2', 'sidebar:', '  order: 0', '---', '', '<!-- Generated by npm run docgen from documentation/catalog/catalog.json. Do not edit. -->', ''];
	out.push('Each card shows what JOID draws, with a link to the page that teaches it and to its reference.', '');
	for (const section of catalog.sections) {
		if (section.cards.every((card) => card.capture === false)) {
			out.push(`## ${section.title}`, '', section.intro, '', `| ${section.columns[0]} | ${section.columns[1]} |`, '|---|---|');
			for (const card of section.cards) {
				out.push(`| [\`${cardName(card)}\`](${reference(card, index).url}) | ${card.text} |`);
			}
			out.push('');
			continue;
		}
		out.push(`## ${section.title}`, '', section.intro, '', '<div class="joid-catalog">');
		for (const card of section.cards) {
			const { url, entry } = reference(card, index);
			const name = cardName(card);
			const shot = shotName(section, card);
			const img = `<img src="/captures/${shot}.webp" alt="${escape(card.alt)}" loading="lazy" width="340" height="300" />`;
			const still = existsSync(join(CAPTURES, `${shot}.still.webp`)) ? `<picture><source srcset="/captures/${shot}.still.webp" media="(prefers-reduced-motion: reduce)" />${img}</picture>` : img;
			const image = card.capture !== false && existsSync(join(CAPTURES, `${shot}.webp`)) ? still : `<div class="joid-card-empty" aria-hidden="true"><code>${escape(name)}</code></div>`;
			const summary = card.type ? entry.summary : '';
			const abstract = card.type && entry.abstract && entry.ancestors.includes('dev.joid.lib.ui.node.Node') ? ` <a class="joid-badge" href="${SKINS}">needs a skin</a>` : '';
			const learn = card.learn.includes('#') ? card.learn.replace('#', '/#') : `${card.learn}/`;
			const links = [`<a href="/${learn}">Learn</a>`, `<a href="${url}">Reference</a>`];
			if (card.example) {
				links.push(`<a href="${EXAMPLES}${card.example}">Example source</a>`);
			}
			out.push('<figure class="joid-card">', image, `<figcaption><a href="${url}"><code>${escape(name)}</code></a>${abstract}${summary ? `<span>${escape(summary).replace(/`([^`]+)`/g, '<code>$1</code>')}</span>` : ''}<small>${links.join(' · ')}</small></figcaption>`, '</figure>');
		}
		out.push('</div>', '');
	}
	return out.join('\n');
}

export function generateCatalog() {
	const catalog = loadCatalog();
	const index = loadIndex();
	for (const file of readdirSync(SCENARIOS).filter((name) => name.startsWith('catalog-'))) {
		rmSync(join(SCENARIOS, file));
	}
	for (const section of catalog.sections) {
		if (section.scene || section.commands) {
			writeFileSync(join(SCENARIOS, `catalog-${section.id}.txt`), `${scenario(section).join('\n')}\n`);
		}
	}
	writeFileSync(PAGE, `${page(catalog, index)}\n`);
}

export function checkCatalog() {
	const catalog = loadCatalog();
	const index = loadIndex();
	const problems = [];
	const listed = new Set(catalog.sections.flatMap((section) => section.cards.filter((card) => card.type).map((card) => card.type)));
	for (const entry of Object.values(index.byFqcn)) {
		const concerned = entry.url.startsWith('/use/') && catalog.roots.some((root) => entry.fqcn === root || entry.ancestors.includes(root));
		if (concerned && !listed.has(entry.fqcn) && !catalog.excluded[entry.fqcn]) {
			problems.push(`${entry.fqcn} has no card in documentation/catalog/catalog.json (add a card, or an "excluded" entry with the reason)`);
		}
	}
	for (const section of catalog.sections) {
		if (!section.complete) {
			continue;
		}
		const entry = index.byFqcn[section.complete];
		const names = new Set(section.cards.map((card) => (card.reference ?? '').split('#')[1]));
		for (const [member, anchor] of Object.entries(entry.members)) {
			if ((/-value-|-constant-/).test(anchor) && !names.has(member)) {
				problems.push(`${section.complete}#${member} has no card in the ${section.id} section`);
			}
		}
	}
	for (const section of catalog.sections) {
		for (const card of section.cards) {
			try {
				reference(card, index);
			} catch (error) {
				problems.push(error.message);
			}
			if (card.capture !== false && !existsSync(join(CAPTURES, `${shotName(section, card)}.webp`))) {
				problems.push(`${shotName(section, card)}.webp is missing, run npm run captures -- catalog-${section.id}`);
			}
			if (card.capture !== false && !card.alt) {
				problems.push(`${shotName(section, card)} has no alt text`);
			}
		}
	}
	return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	withLock(generateCatalog);
}